import {expect,test} from '@playwright/test'
import {baseReady,mapSettled,renderFrames} from './map-readiness'
import {chooseTheme} from './theme-controls'

test('layer toolbar independently previews settings and preserves the desktop reader',async({page},info)=>{
  test.skip(info.project.name!=='desktop','desktop popover alongside the reader')
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/');await baseReady(page);await mapSettled(page)
  const entry=page.getByRole('button',{name:'打开图层面板',exact:true})
  const panel=page.getByRole('complementary',{name:'图层与底图',exact:true})
  await expect(entry).toBeVisible()
  await expect(entry).toHaveAttribute('aria-expanded','false')
  await expect(panel).toHaveCount(0)
  await expect(page.locator('.panel-tabs').getByRole('button',{name:'图层',exact:true})).toHaveCount(0)
  await entry.click()
  await page.screenshot({path:test.info().outputPath('desktop-layer-popover.png')})
  await entry.click()
  await chooseTheme(page,'中国四大高原')
  const scroll=page.locator('.explorer-scroll')
  await scroll.evaluate(element=>element.scrollTop=400)
  await renderFrames(page)
  const scrollTop=await scroll.evaluate(element=>element.scrollTop)
  await entry.click()
  await expect(panel).toBeVisible()
  await expect(page.locator('.topic-reader')).toBeVisible()
  expect(await scroll.evaluate(element=>element.scrollTop)).toBe(scrollTop)
  await page.getByRole('checkbox',{name:'经纬网图层',exact:true}).check()
  await mapSettled(page)
  await expect.poll(()=>page.evaluate(()=>window.__terraAtlas!.map.getLayoutProperty('grid-lines','visibility'))).toBe('visible')
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('terra-atlas-v1')!).layers.grid)).toBe(true)
  await expect(page.locator('.topic-reader')).toHaveAttribute('data-topic-id','china-plateaus')
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(entry).toBeFocused()
  expect(await scroll.evaluate(element=>element.scrollTop)).toBe(scrollTop)
  await entry.click();await entry.click()
  await expect(entry).toHaveAttribute('aria-expanded','false')
  // Place cards move the toolbar inward; its panel must remain reachable too.
  await page.getByRole('combobox',{name:'搜索地理对象'}).fill('长江')
  await page.locator('.search-results>button').first().click()
  await entry.click()
  await expect(panel).toBeInViewport({ratio:1})
  await expect(page.getByRole('button',{name:'关闭图层面板',exact:true})).toBeInViewport({ratio:1})
  await page.screenshot({path:test.info().outputPath('desktop-layer-toolbar.png')})
  expect(errors).toEqual([])
})
